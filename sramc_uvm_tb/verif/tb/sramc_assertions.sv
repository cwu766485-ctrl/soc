`ifndef SRAMC_ASSERTIONS_SV
`define SRAMC_ASSERTIONS_SV

// AHB/SRAMC assertion checker.
//
// This module checks the normal AHB-to-SRAMC functional path: protocol,
// address legality, and bank decode. BIST/DFT is outside this DV scope.
module sramc_assertions (
  input logic        hclk,
  input logic        hresetn,
  input logic        hsel,
  input logic [31:0] haddr,
  input logic [1:0]  htrans,
  input logic [2:0]  hsize,
  input logic        hwrite,
  input logic        hready,
  input logic        hready_resp,
  input logic [1:0]  hresp,
  input logic [3:0]  bank0_csn,
  input logic [3:0]  bank1_csn
);

  default clocking cb @(posedge hclk); endclocking // 每个 posedge hclk，SVA 自动采样一次；
  default disable iff (!hresetn); // reset 有效期间，所有 property 暂停检查；

  // A valid AHB address phase for this slave.  The RTL documents a 64-KiB
  // byte-addressed window and supports only 8/16/32-bit accesses.
  wire valid_transfer   = hsel && hready && htrans[1];
  wire one_bank_selected = ((bank0_csn != 4'hf) ^ (bank1_csn != 4'hf));

  // Design contract: this SRAM controller is zero-wait-state and only returns
  // an AHB OKAY response.
  property p_response_ready;
    hready_resp === 1'b1;
  endproperty

  property p_response_okay;
    hresp === 2'b00;
  endproperty

  // Legal accesses generated by the AHB master/sequence layer.
  property p_supported_access_size;
    valid_transfer |-> hsize inside {3'b000, 3'b001, 3'b010};
  endproperty

  property p_address_in_controller_window;
    valid_transfer |-> haddr[31:16] == 16'h0000;
  endproperty

  property p_halfword_is_aligned;
    valid_transfer && (hsize == 3'b001) |-> haddr[0] == 1'b0;
  endproperty

  property p_word_is_aligned;
    valid_transfer && (hsize == 3'b010) |-> haddr[1:0] == 2'b00;
  endproperty

  // The AHB slave registers address/control.  A valid functional request must
  // therefore select exactly one SRAM bank on the following sampled cycle.
  property p_functional_transfer_selects_one_bank;
    valid_transfer |=> one_bank_selected;
  endproperty

  property p_bank0_bank1_not_selected_together;
    (bank0_csn != 4'hf) |-> bank1_csn == 4'hf;
  endproperty

  property p_bank_csn_encoding_is_legal;
    (bank0_csn inside {4'b1111, 4'b1110, 4'b1101, 4'b1011,
                        4'b0111, 4'b1100, 4'b0011, 4'b0000}) &&
    (bank1_csn inside {4'b1111, 4'b1110, 4'b1101, 4'b1011,
                        4'b0111, 4'b1100, 4'b0011, 4'b0000});
  endproperty

  a_response_ready: assert property (p_response_ready)
    else $error("[SVA][RESPONSE_READY] HREADY_RESP must be high for this zero-wait-state controller");

  a_response_okay: assert property (p_response_okay)
    else $error("[SVA][RESPONSE_OKAY] HRESP must be OKAY for this controller");

  a_supported_access_size: assert property (p_supported_access_size)
    else $error("[SVA][HSIZE] valid AHB transfer used unsupported HSIZE=%b", hsize);

  a_address_in_controller_window: assert property (p_address_in_controller_window)
    else $error("[SVA][ADDR_RANGE] valid AHB address %h is outside the 64-KiB controller window", haddr);

  a_halfword_is_aligned: assert property (p_halfword_is_aligned)
    else $error("[SVA][HALF_ALIGN] halfword access is not 2-byte aligned: %h", haddr);

  a_word_is_aligned: assert property (p_word_is_aligned)
    else $error("[SVA][WORD_ALIGN] word access is not 4-byte aligned: %h", haddr);

  a_functional_transfer_selects_one_bank: assert property (p_functional_transfer_selects_one_bank)
    else $error("[SVA][BANK_SELECT] accepted functional transfer did not select exactly one bank");

  a_bank0_bank1_not_selected_together: assert property (p_bank0_bank1_not_selected_together)
    else $error("[SVA][BANK_CONFLICT] bank0 and bank1 are selected together in functional mode");

  a_bank_csn_encoding_is_legal: assert property (p_bank_csn_encoding_is_legal)
    else $error("[SVA][BANK_CSN] bank chip-select encoding is illegal: bank0=%b bank1=%b",
                bank0_csn, bank1_csn);

  // Assertion coverage documents which protocol/mode situations the regression
  // has actually exercised. It is separate from covergroup functional coverage.
  c_read:        cover property (valid_transfer && !hwrite);
  c_write:       cover property (valid_transfer &&  hwrite);
  c_byte:        cover property (valid_transfer && hsize == 3'b000);
  c_halfword:    cover property (valid_transfer && hsize == 3'b001);
  c_word:        cover property (valid_transfer && hsize == 3'b010);
  c_busy:        cover property (hsel && hready && htrans == 2'b01);

endmodule : sramc_assertions

`endif // SRAMC_ASSERTIONS_SV
